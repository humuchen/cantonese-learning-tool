// 简繁转换函数
function convertSimplifiedToTraditional(text) {
  let result = text;
  // 按长度排序，优先匹配长词组
  const sortedEntries = Object.entries(SIM_TO_TRAD).sort((a, b) => b[0].length - a[0].length);
  for (const [sim, trad] of sortedEntries) {
    result = result.split(sim).join(trad);
  }
  return result;
}

