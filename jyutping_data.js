// 普通话→粤语转换函数
function convertMandarinToCantonese(text) {
  let result = text;
  // 按长度排序，优先匹配长词组
  const sortedEntries = Object.entries(MANDARIN_TO_CANTONESE).sort((a, b) => b[0].length - a[0].length);
  for (const [mandarin, cantonese] of sortedEntries) {
    result = result.split(mandarin).join(cantonese);
  }
  return result;
}

// 主转换函数：简体 → 繁体 → 粤语
function convertToCantonese(text) {
  // 第一步：简体转繁体
  let result = convertSimplifiedToTraditional(text);
  // 第二步：普通话书面语转粤语口语
  result = convertMandarinToCantonese(result);
  return result;
}

